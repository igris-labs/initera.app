import type { IssueQuery } from '../types/issue';
import type { SavedView } from '../types/view';

export function savedViewQuery(view: SavedView): IssueQuery {
  return {
    scope: view.scope,
    triage: false,
    statuses: view.statuses ?? (view.status === 'All statuses' ? [] : [view.status]),
    excludedStatuses: view.excludedStatuses ?? [],
    priorities: view.priorities ?? (view.priority ? [view.priority] : []),
    excludedPriorities: view.excludedPriorities ?? [],
    projects: view.projects ?? (view.project ? [view.project] : []),
    excludedProjects: view.excludedProjects ?? [],
    projectStatuses: view.projectStatuses ?? [],
    excludedProjectStatuses: view.excludedProjectStatuses ?? [],
    projectPriorities: view.projectPriorities ?? [],
    excludedProjectPriorities: view.excludedProjectPriorities ?? [],
    projectLabels: view.projectLabels ?? [],
    excludedProjectLabels: view.excludedProjectLabels ?? [],
    emptyProjectLabels: view.emptyProjectLabels ?? false,
    excludedEmptyProjectLabels: view.excludedEmptyProjectLabels ?? false,
    projectLeads: view.projectLeads ?? [],
    excludedProjectLeads: view.excludedProjectLeads ?? [],
    emptyProjectLead: view.emptyProjectLead ?? false,
    excludedEmptyProjectLead: view.excludedEmptyProjectLead ?? false,
    projectMilestones: view.projectMilestones ?? [],
    excludedProjectMilestones: view.excludedProjectMilestones ?? [],
    emptyProjectMilestones: view.emptyProjectMilestones ?? false,
    excludedEmptyProjectMilestones: view.excludedEmptyProjectMilestones ?? false,
    milestones: view.milestones ?? [],
    excludedMilestones: view.excludedMilestones ?? [],
    emptyMilestone: view.emptyMilestone ?? false,
    excludedEmptyMilestone: view.excludedEmptyMilestone ?? false,
    labels: view.labels ?? (view.label ? [view.label] : []),
    excludedLabels: view.excludedLabels ?? [],
    emptyLabels: view.emptyLabels ?? false,
    excludedEmptyLabels: view.excludedEmptyLabels ?? false,
    due: view.due ?? 'any',
    text: '',
    advancedGroups: view.advancedGroups ?? [],
    filterTree: view.filterTree,
    sortField: view.sortField,
    sortDirection: view.sortDirection,
    includeSubIssues: view.includeSubIssues,
  };
}
